def main():
    with open(INPUT_PATH, encoding="utf-8") as f:
        data = json.load(f)

    # 서울 데이터만 필터
    seoul_data = [r for r in data["data"] if r["시도"] == "서울"]

    # 구별 층별 임대료 수집
    gu_floors = {}  # {구명: {층: [임대료값, ...]}}

    for record in seoul_data:
        상권명 = record["상권명"]
        구명 = SANGKWON_GU_MAP.get(상권명)
        if 구명 is None:
            continue

        if 구명 not in gu_floors:
            gu_floors[구명] = {}

        for 층, vals in record["층별"].items():
            rent = vals.get("임대료_만원per㎡")
            util = vals.get("효용비율_%")
            if rent is None:
                continue
            if 층 not in gu_floors[구명]:
                gu_floors[구명][층] = {"임대료_list": [], "효용비율_list": []}
            gu_floors[구명][층]["임대료_list"].append(rent)
            if util is not None:
                gu_floors[구명][층]["효용비율_list"].append(util)

    # 구별 평균 계산
    result = {}
    for 구명, floors in gu_floors.items():
        result[구명] = {}
        for 층, vals in floors.items():
            rents = vals["임대료_list"]
            utils = vals["효용비율_list"]
            result[구명][층] = {
                "임대료_만원per㎡": round(sum(rents) / len(rents), 2),
                "효용비율_%": round(sum(utils) / len(utils), 1) if utils else None,
            }

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)

    print(f"완료: {len(result)}개 구 처리")
    for 구, floors in sorted(result.items()):
        층1 = floors.get("1층", {}).get("임대료_만원per㎡", "?")
        print(f"  {구}: 1층 평균 {층1}만원/㎡")


if __name__ == "__main__":
    main()
